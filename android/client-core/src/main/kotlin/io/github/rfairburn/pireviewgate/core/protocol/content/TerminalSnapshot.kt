package io.github.rfairburn.pireviewgate.core.protocol.content

/** A cell color as recorded by the native terminal: default, 256-palette index, or RGB. */
enum class TerminalColorMode(val wireValue: String) {
	DEFAULT("default"),
	PALETTE("palette"),
	RGB("rgb"),
	;

	companion object {
		/** The one color mode named by [wireValue], or null when it is not a mode. */
		fun fromWireValue(value: String): TerminalColorMode? = values().firstOrNull { it.wireValue == value }
	}
}

/**
 * A cell color. [value] is a palette index (0-255) or a packed `0xRRGGBB` value,
 * and is always 0 when [mode] is [TerminalColorMode.DEFAULT].
 */
data class TerminalColorSpec(val mode: TerminalColorMode, val value: Int)

/**
 * A contiguous run of cells sharing one attribute bundle within a viewport row.
 *
 * The native serializer omits default attributes and default colors, so an
 * absent attribute means "default" and is never carried as an explicit false.
 */
data class TerminalCellRun(
	/** Inclusive start column (0-based) of the run within the viewport row. */
	val startColumn: Int,
	/** Sanitized text of the run (continuation cells skipped). */
	val text: String,
	/** Foreground color; null when the default foreground. */
	val fg: TerminalColorSpec? = null,
	/** Background color; null when the default background. */
	val bg: TerminalColorSpec? = null,
	val bold: Boolean = false,
	val dim: Boolean = false,
	val italic: Boolean = false,
	val underline: Boolean = false,
	val inverse: Boolean = false,
	val blink: Boolean = false,
	val invisible: Boolean = false,
	val strikethrough: Boolean = false,
	val overline: Boolean = false,
)

/** One row's style runs; rows made only of default attributes are omitted. */
data class TerminalLineStyles(val line: Int, val runs: List<TerminalCellRun>)

/** 0-based hardware cursor position within the viewport frame. */
data class TerminalCursor(val column: Int, val row: Int, val visible: Boolean)

/** Mouse tracking mode of the native terminal (xterm 6 `modes.mouseTrackingMode`). */
enum class MouseTrackingMode(val wireValue: String) {
	NONE("none"),
	X10("x10"),
	VT200("vt200"),
	DRAG("drag"),
	ANY("any"),
	;

	companion object {
		/** The one mode named by [wireValue], or null when it is not a mode. */
		fun fromWireValue(value: String): MouseTrackingMode? = values().firstOrNull { it.wireValue == value }
	}
}

/** Mouse report encoding observed from DECSET/DECRST 1006 and 1016. */
enum class MouseEncodingMode(val wireValue: String) {
	DEFAULT("default"),
	SGR("sgr"),
	SGR_PIXELS("sgr-pixels"),
	;

	companion object {
		/** The one encoding named by [wireValue], or null when it is not an encoding. */
		fun fromWireValue(value: String): MouseEncodingMode? = values().firstOrNull { it.wireValue == value }
	}
}

/**
 * The native terminal's active input-protocol state: effective Kitty keyboard
 * flags, the exact public xterm 6 modes, and bounded observations of
 * modifyOtherKeys and mouse encoding. This is the terminal's own VT state, not
 * telemetry, and it carries no input authority.
 */
data class TerminalInputModes(
	/** Effective Kitty keyboard enhancement flags of the active buffer (0-7). */
	val kittyFlags: Int,
	/** DECCKM (`CSI ?1 h`). */
	val applicationCursorKeys: Boolean,
	/** DECNKM (ESC = / ESC >, `?66 h/l`). */
	val applicationKeypad: Boolean,
	/** `CSI ?2004 h`. */
	val bracketedPaste: Boolean,
	/** Mouse tracking mode. */
	val mouseTracking: MouseTrackingMode,
	/** Xterm modifyOtherKeys mode: 0 disabled, 1 or 2 as set by `CSI >4;N m`. */
	val modifyOtherKeys: Int,
	/** Mouse report encoding. */
	val mouseEncoding: MouseEncodingMode,
)

/**
 * An immutable snapshot of the terminal's visible state. [lines] are full-width
 * serialized rows: sanitized cell text plus only generated, allowlisted SGR
 * sequences, with an explicit leading and trailing reset per row so no row
 * inherits host styling or a previous row's attributes.
 *
 * The SGR in [lines] is generated by the native serializer, never forwarded
 * child bytes. Only the attribute and color forms the native serializer emits
 * are representable here; arbitrary escape or control payloads are refused by
 * [ContentProtocol.decodeTerminalPayload] and [ContentProtocol.encodeTerminalPayload].
 */
data class TerminalFrame(
	val cols: Int,
	val rows: Int,
	val lines: List<String>,
	val cursor: TerminalCursor,
	/** Structured style runs for rows containing non-default attributes; null when absent. */
	val styles: List<TerminalLineStyles>? = null,
	/** Validated PNG placements and payload-free fallback metadata visible in this buffer. */
	val graphics: TerminalGraphicsFrame? = null,
)
