/**
 * Synthetic saved-search memory child (issue #609).
 *
 * Spawned by `tests/session-host-saved-search-memory.test.ts` as an owned child
 * process under a bounded V8 heap. Inside that child it drives the PRODUCTION
 * saved-conversation search path end to end: real `Main` (through the shared
 * canonical base harness), the real `SidebarController` Saved picker, the real
 * public native `Input` from `form-support`/pi-tui, Main's real `saved-search`
 * action handler, the real read-only catalog (`listSavedSessions` +
 * `searchSavedSessions`), and the real composed host frame the picker renders.
 *
 * Every conversation, id, name, caption, transcript, workspace, and date here
 * is independently invented synthetic text generated by this file. No real saved
 * conversation, user corpus, home directory, configuration, network, or model is
 * read or required.
 *
 * The corpus shape mirrors the reported trigger: one saved catalog, then the
 * keystrokes `n`, `l`, `b` refining one query, then a quoted phrase. The
 * invented transcripts are large enough that the lowercase and
 * whitespace-normalized copies of EVERY conversation only fit in the bounded
 * heap when those derived copies stay scoped to one match invocation instead of
 * being retained for the catalog's lifetime.
 *
 * The child asserts only that the production path kept working; it prints one
 * `PI609_EVIDENCE <json>` line and exits 0. The parent test asserts the contract
 * on that evidence. A build that retains the derived message copies dies with a
 * V8 heap exhaustion before it can print anything.
 */
import assert from "node:assert/strict";
import { mkdirSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import type { ProfilePreparer } from "../../src/session-host/profiles";
import { isSavedSessionAdmission, listSavedSessions } from "../../src/session-host/saved-sessions";
import {
  closeWithSignal,
  createHarness,
  ENTER,
  makeMainTestDirectory,
  nextTurn,
  plain,
  ready,
  type MainTestDependencies,
} from "./session-host-main-harness";

/** Compiled entrypoint of this module, relative to the repository root. */
export const CHILD_ENTRY = join("dist-test", "tests", "helpers", "session-host-saved-search-memory-child.js");

/** Prefix of the single evidence line this child prints on stdout. */
export const EVIDENCE_PREFIX = "PI609_EVIDENCE ";

/**
 * Environment variable naming the fixture root this child must use. The parent
 * test owns that exact directory and removes it; a child started without it
 * (an explicit standalone run) creates and removes its own. Ownership is never
 * a shared prefix scan.
 */
export const CHILD_FIXTURE_ROOT_ENV = "PI609_SAVED_SEARCH_FIXTURE_ROOT";

/** Synthetic conversations in the one loaded catalog. */
export const SYNTHETIC_CONVERSATIONS = 17;
/** Invented transcript size per conversation, in code units (all ASCII). */
export const SYNTHETIC_TRANSCRIPT_UNITS = 6 * 1024 * 1024;

/** Transcript-only marker that must never reach any rendered frame. */
const TRANSCRIPT_MARKER = "synthetic-transcript-marker-609";
/** Message-text words joined only by irregular whitespace. */
const PHRASE_HEAD = "quorum";
const PHRASE_TAIL = "seven\t   forge";
const PHRASE_QUERY = `"${PHRASE_HEAD} seven forge"`;
/** Literal message-text tokens carrying the reported incremental keystrokes. */
const NL_TOKEN = "sample-nl-value";
const NLB_TOKEN = "loop-nlb-node";

interface SyntheticConversation {
  readonly file: string;
  readonly id: string;
  readonly name: string;
  readonly cwd: string;
  readonly modified: Date;
  /** Group A names carry the first keystroke literally; Group B names never do. */
  readonly nameCarriesFirstToken: boolean;
}

/**
 * The invented conversations. All but one name carry `n` but never `nl` or
 * `nlb` (and no scattered `nlb`), so the first keystroke answers from the name
 * and the second has to read every conversation's message text. The remaining
 * conversation carries no `n` in its name or id, so even the first keystroke
 * reads its message text.
 */
function syntheticConversations(agentDir: string): SyntheticConversation[] {
  const groupA = ["Alpha", "Bravo", "Charlie", "Delta", "Echo", "Foxtrot", "Golf", "Hotel",
    "India", "Juliet", "Kilo", "Lima", "Mike", "November", "Oscar", "Papa"];
  const rows: SyntheticConversation[] = groupA.map((tag, index) => ({
    file: join(agentDir, "sessions", "proj", `synthetic-a${index}.jsonl`),
    id: `synthetic-saved-609-a${index}`,
    name: `Runbook ${tag}`,
    cwd: join(agentDir, "workspaces", tag.toLowerCase()),
    modified: new Date(Date.UTC(2025, 0, 10 + index, 1)),
    nameCarriesFirstToken: true,
  }));
  rows.push({
    file: join(agentDir, "sessions", "proj", "synthetic-b0.jsonl"),
    id: "legacy-vault-8842",
    name: "Legacy Vault",
    cwd: join(agentDir, "workspaces", "vault"),
    modified: new Date(Date.UTC(2025, 1, 4, 1)),
    nameCarriesFirstToken: false,
  });
  return rows;
}

/** One independently generated transcript of at least the configured size. */
function syntheticTranscript(tag: string): string {
  // Long low-whitespace runs keep the invented transcripts large without making
  // the normalization itself the dominant allocation: what the regression
  // measures is how long the derived copies of EVERY conversation stay alive.
  const block = `synthetic-conversation-${tag}-alpha-beta-gamma-delta-epsilon-zeta-eta-theta-iota-kappa-mu-nu-xi-omicron-pi-rho-sigma-tau-upsilon-phi-chi-psi-omega-${NL_TOKEN}-${NLB_TOKEN}\n`;
  const parts: string[] = [];
  let units = 0;
  while (units < SYNTHETIC_TRANSCRIPT_UNITS) {
    parts.push(block);
    units += block.length;
  }
  // The quoted-phrase target sits mid-corpus with irregular whitespace, so it
  // matches only through the whitespace-normalized view of the message text.
  parts.splice(Math.floor(parts.length / 2), 0, `  ${PHRASE_HEAD}   ${PHRASE_TAIL}\n`);
  parts.push(`${TRANSCRIPT_MARKER} end-of-synthetic-transcript ${tag}`);
  return parts.join("");
}

/** Saved-picker result rows in the rendered frame, top to bottom. */
function renderedResultRows(frameText: string): Array<{ caption: string; selected: boolean }> {
  const rows: Array<{ caption: string; selected: boolean }> = [];
  for (const line of frameText.split("\n")) {
    const match = /^.*?│(> |  )(.+?) \| /.exec(line);
    if (match === null) continue;
    rows.push({ caption: match[2]!.trim(), selected: match[1] === "> " });
  }
  return rows;
}

/** The roster line the left pane currently marks, after any dismissal. */
function rosterMarker(frameText: string): string {
  for (const line of frameText.split("\n")) {
    const left = line.split("│")[0] ?? "";
    if (left.startsWith("> ")) return left.trim();
  }
  return "";
}

async function main(): Promise<void> {
  const suppliedRoot = process.env[CHILD_FIXTURE_ROOT_ENV];
  const ownsRoot = suppliedRoot === undefined || suppliedRoot.length === 0;
  const scratchRoot = ownsRoot ? makeMainTestDirectory("saved-search-memory") : suppliedRoot!;
  if (ownsRoot === false) mkdirSync(scratchRoot, { recursive: true });
  const agentDir = join(scratchRoot, "agent");
  mkdirSync(join(agentDir, "sessions", "proj"), { recursive: true });
  // The keybindings file only remaps host chords; the query box stays the real
  // native Input and the reported keystrokes stay ordinary printable text.
  writeFileSync(join(agentDir, "keybindings.json"), JSON.stringify({
    "tui.select.down": "ctrl+n",
    "tui.select.up": "ctrl+p",
    "app.session.delete": "ctrl+x",
    "app.session.deleteNoninvasive": "ctrl+backspace",
  }), "utf8");

  const conversations = syntheticConversations(agentDir);
  assert.equal(conversations.length, SYNTHETIC_CONVERSATIONS);
  for (const conversation of conversations) {
    mkdirSync(conversation.cwd, { recursive: true });
    // The on-disk record stays tiny: the public SDK listing is what supplies
    // complete message text to the private search index, exactly as production
    // does, so the invented corpus lives here rather than being read anywhere.
    writeFileSync(conversation.file, [
      JSON.stringify({
        type: "session", version: 3, id: conversation.id,
        timestamp: "2025-01-01T00:00:00.000Z", cwd: conversation.cwd,
      }),
      JSON.stringify({
        type: "message", id: "m1",
        message: { role: "user", content: [{ type: "text", text: `First synthetic message ${conversation.name}` }] },
      }),
    ].join("\n") + "\n", "utf8");
  }

  // Generated ONCE and reused by every listing, so no step re-allocates the
  // invented corpus itself; only the derived search views can differ.
  const listedRows = conversations.map((conversation) => ({
    path: conversation.file,
    id: conversation.id,
    cwd: conversation.cwd,
    name: conversation.name,
    firstMessage: `First synthetic message ${conversation.name}`,
    allMessagesText: syntheticTranscript(conversation.name),
    created: new Date("2025-01-01T00:00:00.000Z"),
    modified: conversation.modified,
  }));

  let listingCalls = 0;
  const overrides: MainTestDependencies = {
    createSessionSetup: () => ({
      nativeSetup: false,
      nativeAgentDir: agentDir,
      profileRegistry: {
        prepare: () => { throw new Error("the synthetic child manager must not prepare sessions"); },
      } satisfies ProfilePreparer,
    }),
    listSavedCatalog: async (options) => {
      listingCalls += 1;
      return listSavedSessions({
        agentDir: options.agentDir,
        signal: options.signal,
        listAll: async () => listedRows,
      });
    },
  };

  const harness = createHarness({}, overrides);
  const steps: Array<{ label: string; query: string; captions: string[]; selected: string; focus: string }> = [];
  try {
    const manager = await ready(harness);
    // A taller host keeps every synthetic result inside the picker's visible
    // window, so the rendered order is fully observable.
    harness.terminal.setSize(80, 48);
    const frameText = (): string => plain(harness.writer.frames.at(-1)?.frame);
    const record = async (label: string): Promise<void> => {
      await nextTurn();
      const rows = renderedResultRows(frameText());
      steps.push({
        label,
        query: harness.sidebar?.savedQuery ?? "",
        captions: rows.map((row) => row.caption),
        selected: rows.find((row) => row.selected)?.caption ?? "",
        focus: harness.sidebar?.focus ?? "",
      });
    };
    const waitForRows = async (): Promise<void> => {
      for (let attempt = 0; attempt < 10; attempt += 1) {
        await nextTurn();
        if (renderedResultRows(frameText()).length > 0) return;
      }
    };

    // Open the Saved picker from the default roster selection and wait for the
    // real catalog listing to render.
    harness.terminal.emitInput("\x1b[A"); // New session -> Saved conversations
    harness.terminal.emitInput(ENTER);
    for (let attempt = 0; attempt < 10 && listingCalls === 0; attempt += 1) await nextTurn();
    await waitForRows();
    assert.equal(listingCalls, 1, "Main performed exactly one real catalog listing");
    await record("opened");

    // The reported incremental keystrokes: n, then l, then b.
    harness.terminal.emitInput("n");
    await record("query-n");
    harness.terminal.emitInput("l");
    await record("query-nl");
    harness.terminal.emitInput("b");
    await record("query-nlb");

    // A quoted phrase whose only home is message text with irregular
    // whitespace, then a mixed literal-token plus phrase query.
    harness.terminal.emitInput("\x15"); // native Input Ctrl+U
    await record("cleared");
    harness.terminal.emitInput(PHRASE_QUERY);
    await record("phrase");
    harness.terminal.emitInput("\x15");
    harness.terminal.emitInput(`nlb ${PHRASE_QUERY}`);
    await record("mixed");
    harness.terminal.emitInput("\x15");
    await record("cleared-again");

    // Navigation and dismissal stay usable after the incremental search.
    harness.terminal.emitInput("\x0e"); // ctrl+n
    await record("down");
    harness.terminal.emitInput("\x0e");
    await record("down-again");
    harness.terminal.emitInput("\x10"); // ctrl+p
    await record("up");
    const markerAfterDismissCheck = rosterMarker(frameText());
    harness.terminal.emitInput("\x1b"); // dismiss
    await record("dismissed");
    const rosterMarkerAfterDismiss = rosterMarker(frameText());

    // Reopening the picker runs the real catalog path again, and a deliberate
    // Enter on a navigated row still selects it: one new child, a branded
    // admission receipt, and that restored child becomes the Main owner.
    harness.terminal.emitInput(ENTER);
    for (let attempt = 0; attempt < 10 && listingCalls < 2; attempt += 1) await nextTurn();
    await waitForRows();
    await record("reopened");
    harness.terminal.emitInput("\x0e");
    await record("reopened-down");
    harness.terminal.emitInput(ENTER);
    await nextTurn();
    await nextTurn();

    const created = manager.createOptions.at(-1);
    const memory = process.memoryUsage();
    const evidence = {
      ok: true as const,
      conversations: conversations.map((conversation) => ({
        name: conversation.name,
        id: conversation.id,
        modified: conversation.modified.toISOString(),
        nameCarriesFirstToken: conversation.nameCarriesFirstToken,
      })),
      listingCalls,
      transcriptUnits: SYNTHETIC_TRANSCRIPT_UNITS,
      // Canonical recorded workspace per synthetic conversation, so the parent
      // can prove the opened child came from the highlighted row's own record.
      workspaces: Object.fromEntries(conversations.map((conversation) => [
        conversation.id,
        realpathSync(conversation.cwd),
      ])),
      steps,
      markerBeforeDismiss: markerAfterDismissCheck,
      rosterMarkerAfterDismiss,
      creates: manager.createOptions.length,
      createdWorkspace: created?.workspace ?? null,
      createdAdmission: created?.savedSession !== undefined && isSavedSessionAdmission(created.savedSession),
      createdSessionId: (created?.savedSession as { sessionId?: string } | undefined)?.sessionId ?? null,
      focusAfterOpen: harness.sidebar?.focus ?? "",
      pickerOpenAfterOpen: harness.sidebar?.savedPickerRequestId !== undefined,
      selectedIdAfterOpen: harness.sidebar?.selectedId ?? null,
      transcriptMarkerInFrames: harness.writer.frames.some((entry) => plain(entry.frame).includes(TRANSCRIPT_MARKER)),
      messageTokenInFrames: harness.writer.frames.some((entry) => plain(entry.frame).includes(NL_TOKEN)),
      heapUsedBytes: memory.heapUsed,
      rssBytes: memory.rss,
    };
    process.stdout.write(`${EVIDENCE_PREFIX}${JSON.stringify(evidence)}\n`);
    assert.equal(await closeWithSignal(harness), 0, "Main shuts down cleanly after the synthetic search");
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.stack ?? error.message : String(error)}\n`);
    await closeWithSignal(harness).catch(() => undefined);
    process.exitCode = 1;
  } finally {
    // Only a root this child created itself is removed here; a parent-supplied
    // root belongs to the parent that spawned (and always cleans up) this child.
    if (ownsRoot) rmSync(scratchRoot, { recursive: true, force: true });
  }
  process.exit(process.exitCode ?? 0);
}

if (require.main === module) void main();
